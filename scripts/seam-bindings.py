#!/usr/bin/env python3
# The Fabric Connector's calls into the engine, generated: every `internal static partial` declaration in managed/Aver.Fabric whose
# name is an engine seam function gets a body that calls through the seam's service table (the engine's docs/EXTENSIONS.md,
# "Services"), at the slot the engine's scripts/abi-services.lock gives it. Stdlib only.
#
#   python scripts/seam-bindings.py --engine <Aver Engine checkout> --write   # managed/Aver.Fabric/Generated/Seams.g.cs and extension.json
#   python scripts/seam-bindings.py --engine <Aver Engine checkout> --check   # fail when either is stale or a declaration disagrees with the lock
#
# Every C# parameter and return type is matched against the lock's C type: an int against int32_t, a float[] against a float pointer,
# an `out int` against int32_t*, a UTF-8 string against const char*, and so on. A mismatch, a missing function or a wrong argument count
# stops here, at Fabric's build, instead of in a game. The services this needs, at the lock's versions, are written into extension.json
# (managed.services), so an engine that does not offer them refuses to load the managed half with a reason.
#
# Exits 1 on any problem.

import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "managed", "Aver.Fabric")
OUT = os.path.join(SRC, "Generated", "Seams.g.cs")
MANIFEST = os.path.join(ROOT, "extension.json")
MARK = "// <auto-generated> by scripts/seam-bindings.py from the engine's scripts/abi-services.lock. Do not edit. </auto-generated>"

SCALARS = {
    "int": {"int32_t", "int"}, "uint": {"uint32_t", "unsigned", "unsigned int"}, "long": {"int64_t", "long long"},
    "ulong": {"uint64_t", "unsigned long long"}, "float": {"float"}, "double": {"double"}, "byte": {"uint8_t", "unsigned char", "char", "int8_t"},
    "short": {"int16_t"}, "ushort": {"uint16_t"},
}


def read(p):
    with open(p, encoding="utf-8", newline=None) as f:
        return f.read()


# ---------------------------------------------------------------------------------------------------------------------------------
# the engine side

def read_lock(engine):
    path = os.path.join(engine, "scripts", "abi-services.lock")
    if not os.path.exists(path):
        sys.exit("seam-bindings: %s not found: the engine is older than its extension services (Aver Engine 0.8.1)" % path)
    services, by_fn, cur, cur_name = {}, {}, None, None
    for raw in read(path).split("\n"):
        line = raw.rstrip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("service "):
            _, cur_name, version, dlls = line.split(" ", 3)
            cur = services[cur_name] = {"version": int(version), "dlls": dlls.split(","), "fns": []}
        elif line.startswith("  ") and cur is not None:
            sig = line.strip()
            fn = sig.split("(", 1)[0].split()[-1].lstrip("*")
            by_fn[fn] = (cur_name, len(cur["fns"]), sig)
            cur["fns"].append(fn)
    return services, by_fn


def callback_names(engine):
    names = set()
    for p in glob.glob(os.path.join(engine, "modules", "**", "include", "**", "*.h"), recursive=True):
        names.update(re.findall(r"typedef\s+[^;]*?\(\s*\*\s*(\w+)\s*\)", read(p)))
    return names


def c_types(sig):
    """(return type, [param types]) of a lock signature, normalised: no const, `T*` with no space."""
    head, params = sig.split("(", 1)
    params = params.rsplit(")", 1)[0].strip()
    ret = head.rsplit(None, 1)[0] if " " in head.strip() else head

    def norm(t):
        t = re.sub(r"\bconst\b", " ", t)
        t = re.sub(r"\s*\*\s*", "*", " ".join(t.split()))
        return t.strip()
    out = []
    if params and params != "void":
        for p in split_top(params):
            p = p.strip()
            m = re.match(r"^(.*?[\s*])(\w+)\s*(\[\s*\d*\s*\])?$", p)
            t = m.group(1) if m else p
            if m and m.group(3):
                t += "*"
            out.append(norm(t))
    return norm(ret), out


def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([<":
            depth += 1
        elif ch in ")]>":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


# ---------------------------------------------------------------------------------------------------------------------------------
# the C# side

class Param:
    def __init__(self, text):
        self.text = " ".join(text.split())
        self.utf8 = "LPUTF8Str" in self.text
        t = re.sub(r"\[\s*[A-Za-z][^\]]*\]\s*", "", self.text).strip()   # attributes, not the [] of an array type
        m = re.match(r"^(?:(out|ref|in)\s+)?(.+?)\s+(@?\w+)$", t)
        if not m:
            raise ValueError("parameter not understood: " + text)
        self.mod, self.type, self.name = m.group(1), m.group(2), m.group(3)
        self.local = self.name.lstrip("@")


class Decl:
    def __init__(self, path, cls, ret, name, params, line):
        self.path, self.cls, self.ret, self.name, self.line = path, cls, ret, name, line
        self.params = [Param(p) for p in split_top(params)] if params.strip() else []
        # The implementation repeats no attribute: C# merges both halves' parameter attributes, and a second [MarshalAs] is an error.
        self.decl_params = ", ".join(((p.mod + " ") if p.mod else "") + p.type + " " + p.name for p in self.params)


DECL = re.compile(r"internal\s+static\s+partial\s+([\w\[\]<>?*.]+)\s+(\w+)\s*\(([^;{]*?)\)\s*;", re.S)
CLASS = re.compile(r"\b(?:static\s+)?(?:unsafe\s+)?partial\s+class\s+(\w+)")


def find_decls():
    decls = []
    for p in sorted(glob.glob(os.path.join(SRC, "**", "*.cs"), recursive=True)):
        if os.sep + "Generated" + os.sep in p or os.sep + "obj" + os.sep in p or os.sep + "bin" + os.sep in p:
            continue
        s = read(p)
        classes = [(m.start(), m.group(1)) for m in CLASS.finditer(s)]
        for m in DECL.finditer(s):
            cls = None
            for off, name in classes:
                if off < m.start():
                    cls = name
            decls.append(Decl(os.path.relpath(p, ROOT).replace("\\", "/"), cls, m.group(1), m.group(2), m.group(3), s.count("\n", 0, m.start()) + 1))
    return decls


# ---------------------------------------------------------------------------------------------------------------------------------
# matching and emitting

def base_scalar(cs):
    return cs.rstrip("?").rstrip("[]") if cs.rstrip("?").endswith("[]") else None


def match(cs_type, mod, utf8, c, callbacks):
    """(function-pointer type, ok, why)."""
    t = cs_type
    if mod in ("out", "ref", "in"):
        if t in SCALARS and c.endswith("*") and c[:-1] in SCALARS[t]:
            return t + "*", True, ""
        # a blittable struct by pointer: C# Text3dDesc against C AverText3dDesc*
        if t not in SCALARS and re.fullmatch(r"\w+", t) and c.endswith("*") and c[:-1].lower().endswith(t.lower()):
            return t + "*", True, ""
        return None, False, "%s %s against %s" % (mod, t, c)
    if t in ("string", "string?"):
        if utf8 and c == "char*":
            return "byte*", True, ""
        return None, False, "string (needs [MarshalAs(UnmanagedType.LPUTF8Str)]) against %s" % c
    b = base_scalar(t)
    if b is not None:
        if b in SCALARS and c.endswith("*") and c[:-1] in SCALARS[b]:
            return b + "*", True, ""
        if b in SCALARS and c == "void*":
            return b + "*", True, ""
        return None, False, "%s against %s" % (t, c)
    if t in SCALARS:
        if c in SCALARS[t]:
            return t, True, ""
        return None, False, "%s against %s" % (t, c)
    if t in ("IntPtr", "nint"):
        if c.endswith("*") or c in ("intptr_t", "uintptr_t", "size_t") or c in callbacks:
            return "nint", True, ""
        return None, False, "%s against %s" % (t, c)
    if c in callbacks:
        return "nint", True, ""
    return None, False, "%s against %s (not a type this generator marshals)" % (t, c)


def match_ret(cs, c):
    if cs == "void":
        return ("void", True) if c == "void" else (None, False)
    if cs in SCALARS:
        return (cs, True) if c in SCALARS[cs] else (None, False)
    if cs in ("IntPtr", "nint"):
        return ("nint", True) if c.endswith("*") or c in ("intptr_t", "uintptr_t", "size_t") else (None, False)
    return None, False


def ident(service):
    return "s_" + service.replace(".", "_").replace("-", "_")


def emit(decls, services, by_fn, callbacks):
    problems, bodies, used = [], {}, {}
    for d in decls:
        if d.name not in by_fn:
            continue
        svc, slot, sig = by_fn[d.name]
        cret, cparams = c_types(sig)
        where = "%s:%d %s" % (d.path, d.line, d.name)
        if len(cparams) != len(d.params):
            problems.append("%s: %d parameter(s) in C#, %d in the engine (%s)" % (where, len(d.params), len(cparams), sig))
            continue
        rt, ok = match_ret(d.ret, cret)
        if not ok:
            problems.append("%s: returns %s in C#, %s in the engine (%s)" % (where, d.ret, cret, sig))
            continue
        fptypes, pre, fixed, args, bad = [], [], [], [], False
        for i, (p, c) in enumerate(zip(d.params, cparams)):
            ft, ok, why = match(p.type, p.mod, p.utf8, c, callbacks)
            if not ok:
                problems.append("%s: parameter %d (%s): %s (%s)" % (where, i + 1, p.local, why, sig))
                bad = True
                continue
            fptypes.append(ft)
            n = p.local
            if p.mod in ("out", "ref"):
                if p.mod == "out":
                    pre.append("%s = default;" % p.name)
                fixed.append("fixed (%s p_%s = &%s)" % (ft, n, p.name))
                args.append("p_" + n)
            elif p.type in ("string", "string?"):
                pre.append("byte[]? u_%s = Seams.Utf8(%s);" % (n, p.name))
                fixed.append("fixed (byte* p_%s = u_%s)" % (n, n))
                args.append("p_" + n)
            elif base_scalar(p.type) is not None:
                fixed.append("fixed (%s p_%s = %s)" % (ft, n, p.name))
                args.append("p_" + n)
            elif ft == "nint" and p.type not in ("IntPtr", "nint"):
                pre.append("nint f_%s = %s == null ? 0 : Marshal.GetFunctionPointerForDelegate(%s);" % (n, p.name, p.name))
                args.append("f_" + n)
            else:
                args.append(p.name)
        if bad:
            continue
        used.setdefault(svc, {})[slot] = d.name
        call = "((delegate* unmanaged[Cdecl]<%s>)Seams.Slot(Seams.%s, %d, \"%s v%d\"))(%s)" % (
            ", ".join(fptypes + [rt]), ident(svc), slot, svc, services[svc]["version"], ", ".join(args))
        body = ["    internal static partial %s %s(%s)" % (d.ret, d.name, d.decl_params), "    {"]
        body += ["        " + x for x in pre]
        stmt = ("return " if rt != "void" else "") + call + ";"
        if d.ret in ("IntPtr",) and rt == "nint":
            stmt = "return (IntPtr)" + call + ";"
        for k, fx in enumerate(fixed):
            body.append("        " + "    " * 0 + fx)
        body.append("        " + ("    " if fixed else "") + stmt)
        body.append("    }")
        bodies.setdefault(d.cls, []).append("\n".join(body))

    out = [MARK, "#nullable enable", "#pragma warning disable CS1591", "", "using System;", "using System.Runtime.InteropServices;", "",
           "namespace Aver.Fabric;", "",
           "/// <summary>The engine services Fabric calls through (managed.services in extension.json), handed over by the engine's extension loader.</summary>",
           "internal static unsafe class Seams", "{"]
    req = sorted(used)
    out.append("    /// <summary>The services, at the versions this build was generated against.</summary>")
    out.append("    internal static readonly (string Name, uint Version)[] Required =")
    out.append("    {")
    out += ['        ("%s", %d),' % (s, services[s]["version"]) for s in req]
    out.append("    };")
    out.append("")
    for s in req:
        out.append("    internal static nint[]? %s;" % ident(s))
    out.append("")
    out.append("    // Per service: the names at the slots this build uses (null elsewhere), and the libraries a host without the loader resolves them from.")
    for s in req:
        n = max(used[s]) + 1
        names = ", ".join('"%s"' % used[s][i] if i in used[s] else "null" for i in range(n))
        out.append("    private static readonly string?[] n_%s = { %s };" % (ident(s)[2:], names))
    out.append("")
    out.append("    /// <summary>Takes each service's table from the engine (ExtensionContext.GetService). Throws, naming the service, when one is not offered or")
    out.append("    /// is shorter than this build needs.</summary>")
    out.append("    internal static void Init(Func<string, uint, IntPtr> getService)")
    out.append("    {")
    for s in req:
        out.append('        %s = Take(getService("%s", %d), n_%s, "%s v%d");' % (ident(s), s, services[s]["version"], ident(s)[2:], s, services[s]["version"]))
    out.append("    }")
    out.append("")
    out.append("    /// <summary>For a host without the extension loader (Fabric's own tests): the same slots, resolved by name from the engine's libraries.</summary>")
    out.append("    internal static void InitFromLibraries()")
    out.append("    {")
    for s in req:
        libs = ", ".join('"%s"' % l for l in services[s]["dlls"])
        out.append("        %s = Resolve(new[] { %s }, n_%s);" % (ident(s), libs, ident(s)[2:]))
    out.append("    }")
    out.append("""
    private static nint[] Take(IntPtr table, string?[] names, string service)
    {
        if (table == IntPtr.Zero)
            throw new DllNotFoundException($"the engine does not offer the service {service}, which the Fabric Connector needs (Aver Engine 0.8.1 or later)");
        uint count = *(uint*)((byte*)table + 4);
        if (count < (uint)names.Length)
            throw new DllNotFoundException($"the engine's {service} has {count} functions and the Fabric Connector needs {names.Length}; update the engine");
        var slots = new nint[names.Length];
        nint* fn = (nint*)((byte*)table + 8);
        for (int i = 0; i < slots.Length; i++) slots[i] = fn[i];
        return slots;
    }

    private static nint[] Resolve(string[] libraries, string?[] names)
    {
        var handles = new System.Collections.Generic.List<IntPtr>();
        foreach (string lib in libraries)
            if (NativeLibrary.TryLoad(lib, typeof(Seams).Assembly, null, out IntPtr h)) handles.Add(h);
        var slots = new nint[names.Length];
        for (int i = 0; i < names.Length; i++)
        {
            if (names[i] == null) continue;
            foreach (IntPtr h in handles)
                if (NativeLibrary.TryGetExport(h, names[i]!, out IntPtr p)) { slots[i] = p; break; }
        }
        return slots;
    }

    internal static nint Slot(nint[]? table, int slot, string service)
    {
        nint fn = table != null ? table[slot] : 0;
        if (fn == 0)
            throw new DllNotFoundException($"the engine service {service} was not handed to the Fabric Connector (it is loaded through the engine's extension loader)");
        return fn;
    }

    internal static byte[]? Utf8(string? s)
    {
        if (s == null) return null;
        int n = System.Text.Encoding.UTF8.GetByteCount(s);
        var b = new byte[n + 1];
        System.Text.Encoding.UTF8.GetBytes(s, 0, s.Length, b, 0);
        return b;
    }
}""")
    for cls in sorted(bodies):
        out.append("")
        out.append("internal static unsafe partial class %s" % cls)
        out.append("{")
        out.append("\n\n".join(bodies[cls]))
        out.append("}")
    out.append("")
    return "\n".join(out), problems, {s: services[s]["version"] for s in req}


def manifest_text(text, required):
    data = json.loads(text)
    have = data.get("managed", {}).get("services")
    if have == required:
        return text
    svc = "{ " + ", ".join('"%s": %d' % (k, v) for k, v in sorted(required.items())) + " }"
    if have is None:
        m = re.search(r'("managed"\s*:\s*\{)(.*?)(\}\s*,?\s*\n)', text, re.S)
        inner = m.group(2).rstrip()
        return text[:m.start(2)] + inner + ', "services": ' + svc + " " + text[m.start(3):]
    return re.sub(r'"services"\s*:\s*\{[^}]*\}', '"services": ' + svc, text, count=1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    services, by_fn = read_lock(a.engine)
    callbacks = callback_names(a.engine)
    decls = find_decls()
    text, problems, required = emit(decls, services, by_fn, callbacks)
    unknown = [d for d in decls if d.name.startswith("aver_") and d.name not in by_fn and d.cls not in ("GdextNative",)]
    for d in unknown:
        problems.append("%s:%d %s: not a function of any engine service (scripts/abi-services.lock)" % (d.path, d.line, d.name))
    if problems:
        for p in problems:
            print("seam-bindings: " + p, file=sys.stderr)
        return 1
    mtext = read(MANIFEST)
    new_m = manifest_text(mtext, required)
    if a.check:
        bad = []
        if not os.path.exists(OUT) or read(OUT) != text:
            bad.append("%s is stale: --write regenerates it" % os.path.relpath(OUT, ROOT))
        if new_m != mtext:
            bad.append("extension.json's managed.services is not %s: --write sets it" % json.dumps(required))
        for b in bad:
            print("seam-bindings: " + b, file=sys.stderr)
        if bad:
            return 1
        print("seam bindings ok: %d functions over %d services" % (sum(1 for d in decls if d.name in by_fn), len(required)))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if new_m != mtext:
        with open(MANIFEST, "w", encoding="utf-8", newline="") as f:
            f.write(new_m)
    print("wrote %s (%d functions over %d services: %s)" % (os.path.relpath(OUT, ROOT), sum(1 for d in decls if d.name in by_fn), len(required),
                                                          ", ".join("%s v%d" % kv for kv in sorted(required.items()))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
